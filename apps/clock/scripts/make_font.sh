#!/bin/sh
# Regenerate src/digits_font.c: DejaVu Sans Mono Bold subset to "0-9" and ":"
# (monospaced digits, so the clock does not jitter). Kerning/layout tables are
# dropped on purpose: a leftover empty GPOS makes stb_truetype crash. Needs: pip install fonttools
# DejaVu fonts are under the free Bitstream Vera / DejaVu license.
set -e
cd "$(dirname "$0")/.."
src="${1:-/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf}"
tmp="$(mktemp -d)"
pyftsubset "$src" --text="0123456789:" --layout-features= --no-hinting --drop-tables+=GPOS,GSUB,GDEF,kern \
  --output-file="$tmp/digits.ttf"
python3 - "$tmp/digits.ttf" src/digits_font.c <<'PY'
import sys
data = open(sys.argv[1], "rb").read()
with open(sys.argv[2], "w") as f:
    f.write("/* Generated by scripts/make_font.sh - do not edit. */\n")
    f.write("#include <stddef.h>\n#include <stdint.h>\n\n")
    f.write("const uint8_t digits_font_ttf[] = {\n")
    for i in range(0, len(data), 16):
        f.write("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",\n")
    f.write("};\n\nconst size_t digits_font_ttf_len = sizeof(digits_font_ttf);\n")
PY
rm -rf "$tmp"
echo "wrote src/digits_font.c"
